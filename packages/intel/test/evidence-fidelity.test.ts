import { describe, expect, it } from "vitest";
import { pythonApiDocs, tsApiDocs } from "../src/analyzers/api-docs.ts";
import { findDebtMarkers } from "../src/analyzers/tech-debt.ts";
import { looksGenerated } from "../src/analyzers/types.ts";
import { type FileEntry, markGeneratedBySiblings } from "../src/fs/scan.ts";

describe("evidence excerpts are verbatim source lines", () => {
  it("quotes the undocumented definition itself, with its line number", () => {
    const py = pythonApiDocs("pkg/mod.py", 'def documented():\n    """Yes."""\n\ndef bare(x, y):\n    return x\n');
    expect(py.undocumentedAt).toEqual([{ line: 4, text: "def bare(x, y):" }]);
    const ts = tsApiDocs("src/a.ts", "/** Doc. */\nexport function a() {}\nexport const b = 1;\n");
    expect(ts.undocumentedAt).toEqual([{ line: 3, text: "export const b = 1;" }]);
  });

  it("keeps a TODO's tag and comment marker as written", () => {
    const [m] = findDebtMarkers("crates/ruff/src/x.rs", "    // TODO(brent) handle methods with decorators\n");
    expect(m?.raw).toBe("// TODO(brent) handle methods with decorators");
    expect(m?.text).toBe("handle methods with decorators");
  });
});

describe("generated sources", () => {
  const entry = (path: string): FileEntry => ({ path, ext: path.slice(path.lastIndexOf(".")), language: undefined, sizeBytes: 1, category: "source", vendored: false });

  it("treats output beside its grammar or schema as vendored", () => {
    const files = [entry("src/lexer.c"), entry("src/lexer.l"), entry("src/parser.c"), entry("src/parser.y"), entry("api/v1/user.pb.go"), entry("api/v1/user.proto"), entry("src/main.c")];
    markGeneratedBySiblings(files, new Set(files.map((f) => f.path)));
    expect(files.filter((f) => f.vendored).map((f) => f.path)).toEqual(["src/lexer.c", "src/parser.c", "api/v1/user.pb.go"]);
  });

  it("recognises generated-file banners and #line directives near the top, only in comments", () => {
    expect(looksGenerated('#line 1 "src/lexer.c"\n#include <stdio.h>\n')).toBe(true);
    expect(looksGenerated("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage v1\n")).toBe(true);
    expect(looksGenerated("# @generated by uv\nfoo = 1\n")).toBe(true);
    expect(looksGenerated("# Documentation\n\nThis site is generated by our tool, which you can extend.\n")).toBe(false);
    expect(looksGenerated("def generated_by(x):\n    return x\n")).toBe(false);
  });
});

describe("dependency updates already in flight", () => {
  it("finds an open PR whose title names the package, and nothing for near-miss names", async () => {
    const { openPrFor } = await import("../src/analyzers/dependencies.ts");
    const pr = (number: number, title: string, state = "OPEN") => ({ number, title, state, url: `https://github.com/o/r/pull/${number}`, isDraft: false, author: { login: "dependabot[bot]", isBot: true } }) as never;
    const prs = [pr(30, "chore(deps): bump esbuild from 0.27.7 to 0.28.2"), pr(31, "Bump @babel/core from 7.1 to 7.2"), pr(29, "bump esbuild-wasm to 0.28", "CLOSED")];
    expect(openPrFor(prs, "esbuild")?.number).toBe(30);
    expect(openPrFor(prs, "@babel/core")?.number).toBe(31);
    expect(openPrFor(prs, "esbuild-wasm")).toBeUndefined();
    expect(openPrFor(prs, "build")).toBeUndefined();
  });
});
