import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import type { GitHubApi } from "../src/github/client.ts";
import { analyzeRepository } from "../src/index.ts";
import { AI_POLICY_FILE, findAiPolicy } from "../src/profile/ai-policy.ts";
import { FixtureRepo } from "./helpers/fixture-repo.ts";

// Paraphrases of the shapes real policies take (Gentoo, NetBSD, Servo, QEMU, Zig, Ghostty, nixpkgs, LLVM).
const policy = (text: string, path = "CONTRIBUTING.md") => findAiPolicy([{ path, text }]);

describe("findAiPolicy", () => {
  it("finds refusals of AI-generated contributions, however they are phrased", () => {
    for (const text of [
      "Our policy is to decline any contributions that include or derive from AI-generated content.",
      "Contributing any content created with the help of artificial intelligence tools is expressly forbidden.",
      "Code generated by a large language model must not be committed without prior written approval from the core team.",
      "Contributions must not include content generated by large language models or tools like ChatGPT.",
      "## Rules\n\n- No LLMs for issues.\n- No LLMs for patches or pull requests.",
      "We do not accept AI-generated pull requests, even if they were reviewed.",
    ]) {
      const found = policy(text);
      expect(found.stance, text).toBe("forbidden");
      expect(found.statements[0]?.path).toBe("CONTRIBUTING.md");
    }
  });

  it("does not read a rule for using AI, or a ban on AI media or AI issues, as a refusal", () => {
    for (const text of [
      "If you cannot explain your change without the help of AI tools, do not contribute to this project.",
      "No AI-generated media is allowed (art, images, videos, audio). Using AI to write code is fine.",
      "- **No AI-generated media is allowed (art, images, videos, etc.).** Text and code are the only acceptable AI-generated content.",
      "No LLMs for issues.",
      "We do not forbid AI-assisted patches, but you are responsible for every line of them.",
      "AI-generated code is not accepted unless a person has reviewed and tested it.",
    ]) {
      expect(policy(text).stance, text).not.toBe("forbidden");
    }
  });

  it("finds disclosure rules and the commit trailer a project asks for", () => {
    const ghostty = policy("- **Any use of AI must be disclosed.** Say which tool you used and how much of the work it did.");
    expect(ghostty.stance).toBe("disclose");
    expect(ghostty.statements[0]?.text).toContain("Any use of AI must be disclosed.");
    expect(policy("All AI use must be disclosed: name the tool (e.g. an assistant or an agent) you used.").statements[0]?.text).toContain("(e.g. an assistant or an agent) you used.");
    const nixpkgs = policy("Commits made with LLM-based tools must carry an `Assisted-by:` trailer naming the tool and the model.");
    expect(nixpkgs).toMatchObject({ stance: "disclose", trailer: "Assisted-by" });
    // The same trailer in a list of trailers for people's help is not an AI rule.
    expect(policy("Use these trailers where they fit: `Acked-by:`, `Assisted-by:`, `Reported-by:`.\n\nWe review every patch.").trailer).toBeUndefined();
  });

  it("notes when starter issues are kept for people, without refusing the whole project", () => {
    const llvm = policy("Contributors may use whatever tools they like, but must review all LLM-generated code before asking for a review.\n\nAI tools must not be used to fix issues labelled good first issue.", "llvm/docs/AIToolPolicy.md");
    expect(llvm).toMatchObject({ stance: "mentioned", starterIssuesExcluded: true });
    expect(llvm.statements.map((s) => s.text)).toEqual(["AI tools must not be used to fix issues labelled good first issue.", "Contributors may use whatever tools they like, but must review all LLM-generated code before asking for a review."]);
  });

  it("says not_found when nothing is said about using AI, including in an AI library's own docs", () => {
    expect(policy("This library makes it easy to train AI models. Pull requests are welcome!")).toEqual({ stance: "not_found", starterIssuesExcluded: false, statements: [] });
    expect(policy("Changes to the ai module must not break the public API.")).toMatchObject({ stance: "not_found" });
    expect(findAiPolicy([])).toMatchObject({ stance: "not_found" });
  });

  it("quotes refusals first, each sentence once, across files", () => {
    const found = findAiPolicy([
      { path: "README.md", text: "Please disclose any AI assistance in your pull request." },
      { path: "CONTRIBUTING.md", text: "Please disclose any AI assistance in your pull request. We do not accept AI-generated patches." },
    ]);
    expect(found.stance).toBe("forbidden");
    expect(found.statements).toEqual([
      { path: "CONTRIBUTING.md", text: "We do not accept AI-generated patches." },
      { path: "README.md", text: "Please disclose any AI assistance in your pull request." },
    ]);
  });
});

describe("AI_POLICY_FILE", () => {
  it("matches the names projects give their AI policies", () => {
    for (const path of ["AI_POLICY.md", "docs/ai-policy.md", "llvm/docs/AIToolPolicy.md", "LLM_POLICY.md", ".github/AI_USAGE.md", "GENERATIVE_AI_POLICY.rst"]) expect(AI_POLICY_FILE.test(path), path).toBe(true);
    for (const path of ["src/ai/policy.ts", "MAINTAINERS.md", "docs/email-policy.md", "aipolicy.json"]) expect(AI_POLICY_FILE.test(path), path).toBe(false);
  });
});

describe("the profile", () => {
  it("carries the AI policy, read from the project's own policy file", async () => {
    const repo = await FixtureRepo.create();
    const cacheDir = await mkdtemp(join(tmpdir(), "gitgoblin-cache-"));
    try {
      await repo.commit({ files: { "README.md": "# r\n", "AI_POLICY.md": "# AI policy\n\nWe do not accept AI-generated pull requests.\n", "r/__init__.py": "x = 1\n" } });
      const github = {
        stats: { requests: 0, remaining: 5000 },
        rest: async (path: string) => {
          if (path === "/repos/o/r") return { owner: { login: "o" }, name: "r", default_branch: "main", description: "d", homepage: null, topics: [], stargazers_count: 1, forks_count: 0, subscribers_count: 0, open_issues_count: 0, license: null, archived: false, disabled: false, fork: false, is_template: false, has_issues: true, size: 1, created_at: "2020-01-01T00:00:00Z", pushed_at: "2026-10-01T00:00:00Z" };
          throw new Error("not needed");
        },
        graphql: async () => {
          throw new Error("not needed");
        },
      } as unknown as GitHubApi;
      const report = await analyzeRepository({ owner: "o", name: "r", localPath: repo.dir }, { github, cacheDir, checkLinks: false, dependencyChecks: false });
      expect(report.profile.welcomeness.rules.aiPolicy).toEqual({ stance: "forbidden", starterIssuesExcluded: false, statements: [{ path: "AI_POLICY.md", text: "We do not accept AI-generated pull requests." }] });
    } finally {
      await repo.cleanup();
      await rm(cacheDir, { recursive: true, force: true });
    }
  }, 60_000);
});
